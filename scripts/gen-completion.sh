# Filter a newline-separated candidate list by the literal prefix $2; the
# caller owns the loop (no bash-style namerefs in zsh).
# Stripped value token of a flag ("SECURE|COMMUNITY", "path|-", "type", "").
_rp_value_token() { # $1 res, $2 fullverb, $3 flag
  local meta token
  meta="$(_rp_meta "$1" "$2" "$3")"
  token="${meta#*$'\t'}"
  token="${token#<}"
  printf '%s' "${token%>}"
}

# Stripped first-positional token of a verb's usage record ("" when none).
_rp_positional_token() { # $1 res, $2 fullverb
  local token
  token="$(_rp_usage_token "$1" "$2")"
  token="${token#<}"
  printf '%s' "${token%>}"
}

_rp() {
  local cur="${words[CURRENT]}"
  local i w res="" verb="" sub="" npos=0 skip=0 lastflag="" meta kind token
  local fullverb cand
  local -a m
  for ((i = 2; i < CURRENT; i++)); do
    w="${words[i]}"
    case "$w" in
    --)
      npos=999
      skip=0
      ;;
    -*)
      fullverb="$verb${sub:+ $sub}"
      meta=""
      [[ -n "$res" && -n "$fullverb" ]] && meta="$(_rp_meta "$res" "$fullverb" "${w#--}")"
      kind="${meta%%$'\t'*}"
      if [[ "$kind" == "value" ]]; then
        skip=1
        lastflag="${w#--}"
      else
        skip=0
      fi
      ;;
    *)
      if ((skip)); then
        skip=0
        continue
      fi
      if [[ -z "$res" ]]; then
        res="$w"
      elif [[ -z "$verb" ]]; then
        verb="$w"
      elif [[ -z "$sub" && -n "$verb" ]] && _rp_is_group "$res" "$verb"; then
        sub="$w"
      else
        npos=$((npos + 1))
      fi
      ;;
    esac
  done
  fullverb="$verb${sub:+ $sub}"

  m=()
  if ((skip)); then
    # Completing the value of $lastflag. File-shaped tokens need _files in
    # this (completion) context — a $() capture would lose its output.
    token="$(_rp_value_token "$res" "$fullverb" "$lastflag")"
    local _nl=$'\n'
    case "$token" in
    file* | path* | dir*) _files -r '/' && return 0 ;;
    *'|'*) cand="${token//|/$_nl}" ;;
    *)
      [[ "$lastflag" == "cost-center" ]] &&
        cand="$(rp _complete "$res" "$fullverb" cost-center 2>/dev/null)"
      ;;
    esac
  elif [[ "$cur" == -* ]]; then
    [[ -n "$res" && -n "$fullverb" ]] &&
      cand="$(_rp_rows "$res" "$fullverb" | awk -F'\t' '{print "--"$1}')"
  elif [[ -z "$res" ]]; then
    cand="$(_rp_resources)"
  elif [[ -z "$verb" ]]; then
    cand="$(_rp_verbs "$res")"
  elif [[ -z "$sub" && -n "$verb" ]] && _rp_is_group "$res" "$verb"; then
    cand="$(_rp_subs "$res" "$verb")"
  elif ((npos == 0)); then
    token="$(_rp_positional_token "$res" "$fullverb")"
    case "$token" in
    file* | path* | dir*) _files -r '/' && return 0 ;;
    id | endpoint | name) cand="$(rp _complete "$res" "$fullverb" - 2>/dev/null)" ;;
    esac
  fi
  local c
  while IFS= read -r c; do
    [[ -z "$c" || "$c" != "$cur"* ]] && continue
    m+=("$c")
  done <<<"${cand:-}"
  ((${#m[@]})) && compadd -- "${m[@]}"
  return 0
}

# Sourcing this file registers the completion; the #compdef header above also
# allows an fpath install (copy to ~/.rp/completions and add that dir to
# $fpath before compinit).
compdef _rp rp 2>/dev/null || true
EOF
  } >"$out"
}

mkdir -p "$OUT_DIR"
emit_bash "$OUT_DIR/rp.bash"
emit_zsh "$OUT_DIR/_rp"
printf '%s\n' "$OUT_DIR/rp.bash" "$OUT_DIR/_rp"
